from datetime import datetime
from sqlalchemy import Column, Integer, String, Boolean, DateTime, ForeignKey, Float, Text
from sqlalchemy.orm import relationship
from app.database import Base

class SensorReading(Base):
    __tablename__ = "sensor_readings"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, ForeignKey("devices.id", ondelete="CASCADE"), index=True, nullable=False)
    temperature_c = Column(Float, nullable=True)
    humidity_percent = Column(Float, nullable=True)
    humidity_pct = Column(Float, nullable=True)  # Backward compatibility alias
    sensor_status = Column(String(30), default="VALID")  # "VALID", "SENSOR_ERROR", "DISCONNECTED"
    mq135_raw = Column(Integer, nullable=True)  # Actual MQ-135 raw analog ADC reading (0-1023)
    mq135_ppm = Column(Float, nullable=True)  # Raw / normalized relative air-quality index
    mq135_status = Column(String(30), default="NORMAL")  # "NORMAL", "MODERATE", "POOR_AIR_QUALITY"
    recorded_at = Column(DateTime, nullable=True)  # Timestamp generated by ESP32 hardware
    received_at = Column(DateTime, default=datetime.utcnow, index=True)  # Server timestamp
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)  # Legacy alias
    data_freshness = Column(String(20), default="LIVE")  # "LIVE", "STALE", "OFFLINE", "ERROR"

    device = relationship("Device", back_populates="sensor_readings")

class GPSLocation(Base):
    __tablename__ = "gps_locations"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, ForeignKey("devices.id", ondelete="CASCADE"), index=True, nullable=False)
    latitude = Column(Float, nullable=True)
    longitude = Column(Float, nullable=True)
    satellites = Column(Integer, nullable=True)
    gps_fix = Column(Boolean, default=False)
    altitude_m = Column(Float, nullable=True)
    altitude = Column(Float, nullable=True)  # Legacy alias
    speed = Column(Float, nullable=True)
    recorded_at = Column(DateTime, nullable=True)  # Hardware GPS timestamp
    received_at = Column(DateTime, default=datetime.utcnow, index=True)  # Server timestamp
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)  # Legacy alias
    is_valid = Column(Boolean, default=True)

    device = relationship("Device", back_populates="gps_locations")

class FallEvent(Base):
    __tablename__ = "fall_events"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, ForeignKey("devices.id", ondelete="CASCADE"), index=True, nullable=False)
    farmer_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    accel_x = Column(Float, nullable=True)
    accel_y = Column(Float, nullable=True)
    accel_z = Column(Float, nullable=True)
    gyro_x = Column(Float, nullable=True)
    gyro_y = Column(Float, nullable=True)
    gyro_z = Column(Float, nullable=True)
    event_type = Column(String(50), default="POSSIBLE_FALL")  # "POSSIBLE_FALL", "MANUAL_SOS", "HIGH_IMPACT"
    confirmed = Column(Boolean, default=False)
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)

    device = relationship("Device", back_populates="fall_events")

class EmergencyAlert(Base):
    __tablename__ = "emergency_alerts"

    id = Column(Integer, primary_key=True, index=True)
    farmer_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    device_id = Column(Integer, ForeignKey("devices.id", ondelete="SET NULL"), nullable=True)
    alert_type = Column(String(50), default="POSSIBLE_FALL")  # "POSSIBLE_FALL", "MANUAL_SOS", "HAZARDOUS_AIR"
    status = Column(String(30), default="ACTIVE")  # "ACTIVE", "DISPATCHED", "RESOLVED"
    message = Column(Text, nullable=False)
    latitude = Column(Float, nullable=True)
    longitude = Column(Float, nullable=True)
    image_id = Column(Integer, nullable=True)
    dispatched_at = Column(DateTime, nullable=True)
    resolved_at = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, index=True)

    device = relationship("Device", back_populates="emergency_alerts")
